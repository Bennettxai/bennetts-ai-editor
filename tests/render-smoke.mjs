// Run after `npm run demo` (or `npm run render -- demo`). Checks the real delivered MP4.
import assert from 'node:assert/strict';
import fs from 'node:fs';
import {spawnSync} from 'node:child_process';
const edit=JSON.parse(fs.readFileSync('projects/demo/edit.json','utf8'));
const ratio=edit.format?.fps??'30/1';
const [numerator,denominator=1]=String(ratio).split('/').map(Number),fps=numerator/denominator;
const width=edit.format?.resolution==='4k'?2160:1080,height=width*16/9;
const expectedFrames=edit.clips.reduce((n,c)=>n+Math.round(c.end*fps)-Math.round(c.start*fps),0);
const probe=spawnSync('ffprobe',['-v','error','-show_streams','-show_format','-of','json','output/demo.mp4'],{encoding:'utf8'});
assert.equal(probe.status,0,probe.stderr);
const data=JSON.parse(probe.stdout);
const video=data.streams.find(s=>s.codec_type==='video');
assert.equal(video.width,width);assert.equal(video.height,height);
const [actualN,actualD]=video.r_frame_rate.split('/').map(Number);
assert.ok(Math.abs(actualN/actualD-fps)<1e-9);
assert.equal(Number(video.nb_frames),expectedFrames);
assert.ok(data.streams.some(s=>s.codec_type==='audio'));
assert.ok(Math.abs(Number(data.format.duration)-expectedFrames/fps)<0.1);
const loud=spawnSync('ffmpeg',['-hide_banner','-nostats','-i','output/demo.mp4','-af','ebur128','-f','null','-'],{encoding:'utf8'});
const lufs=Number(/I:\s+(-?[\d.]+) LUFS/.exec(loud.stderr.slice(loud.stderr.lastIndexOf('Summary:')))[1]);
assert.ok(Math.abs(lufs+14)<=1,`demo mastered to ${lufs} LUFS, want -14 ± 1`);
console.log(`Real demo MP4 verified: ${width}×${height}, ${ratio}fps, ${expectedFrames} frames, audio at ${lufs} LUFS.`);
